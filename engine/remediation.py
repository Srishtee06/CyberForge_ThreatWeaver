"""
Auto-Generated Remediation Code Engine (Chat Feature 2)
Generates ready-to-run copyable firewall rules (FortiOS, Cisco, Palo Alto)
and Windows PowerShell containment scripts based on incident indicators.
"""

from typing import Dict, List, Any


class RemediationEngine:
    def __init__(self):
        pass

    def generate_remediation_playbook(self, incident: Dict[str, Any]) -> Dict[str, Any]:
        """
        Produces copyable, multi-platform defensive scripts and CLI commands.
        """
        inc_id = incident.get("id", "INC-001")
        nodes = incident.get("nodes", [])
        external_ips = [n for n in nodes if not n.startswith("10.10.")]
        internal_hosts = [n for n in nodes if n.startswith("10.10.")]
        users = incident.get("users_involved", [])
        techniques = incident.get("techniques", [])

        # 1. FortiGate CLI Rules
        fortigate_lines = [
            f"# ==========================================================",
            f"# FortiOS Automated Remediation Script for {inc_id}",
            f"# Generated by CyberForge Defense Engine",
            f"# ==========================================================",
            "config firewall address"
        ]
        for ip in external_ips[:5]:
            fortigate_lines.extend([
                f'    edit "MALICIOUS_{ip}"',
                f'        set subnet {ip}/32',
                f'        set comment "Automated block for {inc_id}"',
                f'    next'
            ])
        fortigate_lines.extend([
            "end",
            "config firewall addrgrp",
            '    edit "CYBERFORGE_ACTIVE_THREATS"',
        ])
        for ip in external_ips[:5]:
            fortigate_lines.append(f'        append member "MALICIOUS_{ip}"')
        fortigate_lines.extend([
            "    next",
            "end",
            "config firewall policy",
            "    edit 999",
            '        set name "CYBERFORGE_DROP_POLICY"',
            '        set srcintf "wan1"',
            '        set dstintf "any"',
            '        set srcaddr "CYBERFORGE_ACTIVE_THREATS"',
            '        set dstaddr "all"',
            '        set action deny',
            '        set schedule "always"',
            '        set service "ALL"',
            '        set logtraffic all',
            "    next",
            "end"
        ])
        fortigate_cli = "\n".join(fortigate_lines)

        # 2. Windows PowerShell Incident Response Script
        ps_lines = [
            f"<#",
            f" .SYNOPSIS",
            f"   CyberForge Automated Host Containment & Eviction Playbook",
            f"   Incident: {inc_id} | Priority: CRITICAL",
            f" .DESCRIPTION",
            f"   Terminates active adversary sessions, disables compromised credentials,",
            f"   and blocks lateral movement ports locally.",
            f"#>",
            "$ErrorActionPreference = 'SilentlyContinue'",
            "Write-Host '[*] Initiating CyberForge Emergency Containment...' -ForegroundColor Red",
            ""
        ]

        if users:
            ps_lines.append("# [Step 1] Disable Compromised User Accounts")
            for u in users:
                if u not in ("unknown", "none"):
                    ps_lines.append(f'Disable-LocalUser -Name "{u}" -Confirm:$false')
                    ps_lines.append(f"Write-Host '[+] Disabled local account: {u}' -ForegroundColor Yellow")

        ps_lines.extend([
            "",
            "# [Step 2] Terminate Malicious Remote Processes & Injected Beacons",
            "$SuspiciousProcesses = @('powershell', 'cmd', 'wmic', 'cscript', 'vssadmin', 'rundll32', 'cobalt')",
            "Get-Process -IncludeUserName | Where-Object { $SuspiciousProcesses -contains $_.ProcessName } | Stop-Process -Force",
            "Write-Host '[+] Evicted rogue execution trees' -ForegroundColor Green",
            "",
            "# [Step 3] Apply Local Host-Level Firewall Blocks"
        ])

        for ip in external_ips[:5]:
            ps_lines.append(
                f'New-NetFirewallRule -DisplayName "CyberForge-Block-{ip}" '
                f'-Direction Inbound -Action Block -RemoteAddress "{ip}" -Protocol Any'
            )

        ps_lines.extend([
            "",
            "# [Step 4] Sever SMB & RDP Lateral Movement Listeners",
            'Set-ItemProperty -Path "HKLM:\\System\\CurrentControlSet\\Control\\Terminal Server" -Name "fDenyTSConnections" -Value 1',
            "Write-Host '[+] RDP Lateral Movement port closed' -ForegroundColor Green",
            "Write-Host '[+] Incident Containment Complete.' -ForegroundColor Cyan"
        ])
        powershell_script = "\n".join(ps_lines)

        # 3. Cisco IOS / ASA Commands
        cisco_lines = [
            f"! Cisco IOS / ASA Quarantine ACL for {inc_id}",
            "configure terminal"
        ]
        for ip in external_ips[:5]:
            cisco_lines.append(f"access-list CYBERFORGE_BLOCK line 1 extended deny ip host {ip} any")
        cisco_lines.extend([
            "access-group CYBERFORGE_BLOCK in interface outside",
            "end",
            "write memory"
        ])
        cisco_cli = "\n".join(cisco_lines)

        return {
            "incident_id": inc_id,
            "target_threat_actors": external_ips,
            "impacted_internal_hosts": internal_hosts,
            "compromised_accounts": users,
            "playbooks": {
                "fortigate_cli": fortigate_cli,
                "powershell": powershell_script,
                "cisco_ios": cisco_cli
            }
        }

